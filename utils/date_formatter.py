"""
Утилиты для форматирования дат и времени.
"""

from datetime import datetime


def format_current_datetime() -> str:
    """
    Форматирует текущую дату и время в формате: "15 февраля 2026, Вс, 11:30"
    
    Returns:
        Строка с отформатированной датой и временем
    """
    now = datetime.now()
    # Названия месяцев на русском (родительный падеж)
    months = [
        "января", "февраля", "марта", "апреля", "мая", "июня",
        "июля", "августа", "сентября", "октября", "ноября", "декабря"
    ]
    # Названия дней недели на русском (сокращенные)
    weekdays = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"]
    
    formatted_date = (
        f"{now.day} {months[now.month - 1]} {now.year}, "
        f"{weekdays[now.weekday()]}, "
        f"{now.hour:02d}:{now.minute:02d}"
    )
    return formatted_date

